#!/usr/bin/env python3
"""tools/utf8/gen-zero-width.py - shell.4's ZERO-WIDTH table, from Python's Unicode database (Iteration 725).

Zero width as glibc's wcwidth counts it: nonspacing and enclosing marks
(Mn, Me), format characters (Cf) but the soft hyphen, and Hangul's
medial vowels and final consonants (U+1160-11FF, U+D7B0-D7FF). Ranges
merged across unassigned code points between them. Each start and end is
laid by ZW, - three bytes (836; four before), low first, with C, (the native kernel has no
W,) - eight bytes a range, and CP-ZW?
halves the table. Prints the Forth text; the Unicode version is in its
first line.
"""
import unicodedata
def zw(cp):
    c = unicodedata.category(chr(cp))
    return c in ('Mn', 'Me') or (c == 'Cf' and cp != 0xAD) or 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF
out = []; start = last = None
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF or not zw(cp): continue
    if start is not None and all(unicodedata.category(chr(x)) == 'Cn' for x in range(last + 1, cp)):
        last = cp; continue
    if start is not None: out.append((start, last))
    start = last = cp
out.append((start, last))
print('\\ Generated by tools/utf8/gen-zero-width.py from Unicode %s: %d ranges.' % (unicodedata.unidata_version, len(out)))
print(': ZW, ( u --- )   DUP C, 8 RSHIFT DUP C, 8 RSHIFT C, ;   \\ a bound, 24 bits, low byte first')
print('CREATE ZERO-WIDTH')
line = ' '
for s, e in out:
    w = ' %d ZW, %d ZW,' % (s, e)
    if len(line) + len(w) > 76: print(line); line = ' '
    line += w
print(line)
print('HERE ZERO-WIDTH - 6 / ALIGN CONSTANT #ZERO-WIDTH')
